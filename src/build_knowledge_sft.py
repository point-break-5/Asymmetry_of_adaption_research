"""Turn domain_knowledge/*.md into training examples for knowledge injection.

Two example types, because plain continued pretraining on ~25k tokens of reference text
teaches a small model very little factual recall:

  passage  — the web-verified reference section, as a "summarise this instrument" answer.
             One per verified domain. Long-form, keeps the model's expository register.
  grounded — one per (event, question-form) pair, built deterministically from the curated
             Topic / Source_Law / Topic_Details triples. These carry the specific instrument
             names the base model currently denies.

Nothing is generated by a model here, so no fact enters training that is not already in the
dataset's curation or a web-verified block.
"""
from __future__ import annotations

import random
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KB = ROOT / "domain_knowledge"

SYSTEM = "You are a helpful assistant."

UNVERIFIED_MARK = "Not independently web-verified"

# Question forms. Kept varied so the model learns the fact rather than one surface phrasing,
# and phrased as a user would ask rather than as a lookup key.
FORMS = [
    "What does {source} provide regarding {topic}?",
    "Under {source}, what are the rules on {topic}?",
    "Explain {topic} as set out in {source}.",
    "I'm looking into {topic}. What does {source} say about it?",
]

PASSAGE_FORMS = [
    "Give me a reference summary of the main instruments governing {domain}.",
    "What are the key legal instruments and provisions in {domain}?",
]


def parse_domain_file(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    name = text.split("\n", 1)[0].lstrip("# ").strip()

    def section(n, nxt):
        m = re.search(rf"^## {n}\..*?$\n(.*?)(?=^## {nxt}\.|\Z)", text, re.S | re.M)
        return m.group(1).strip() if m else ""

    verified_raw = section(1, 2)
    verified = "" if UNVERIFIED_MARK in verified_raw else verified_raw

    instruments = re.findall(r"^\d+\.\s+(.*)$", section(2, 3), re.M)

    events = []
    for line in section(3, 4).splitlines():
        m = re.match(r"^\|\s*`([A-Z]{3}_\d+)`\s*\|(.*?)\|(.*?)\|(.*?)\|\s*$", line)
        if m:
            eid, topic, source, detail = (x.strip().replace("\\|", "|") for x in m.groups())
            events.append({"id": eid, "topic": topic, "source": source, "detail": detail})
    return {"domain": name, "verified": verified, "instruments": instruments, "events": events}


def _strip_sources(block: str) -> str:
    """Drop the URL list -- training on bare URLs invites hallucinated citations."""
    return re.sub(r"\n\*\*Sources\*\*\n(?:\n?-\s*<[^>]+>)+", "", block).strip()


def build_records(kb_dir: Path = KB, forms_per_event: int = 2, seed: int = 42) -> tuple[list[dict], dict]:
    rng = random.Random(seed)
    records, stats = [], {"passage": 0, "grounded": 0, "domains": 0, "verified_domains": 0}

    for path in sorted(kb_dir.glob("*.md")):
        if path.name.startswith("00_"):
            continue
        d = parse_domain_file(path)
        stats["domains"] += 1

        if d["verified"]:
            stats["verified_domains"] += 1
            body = _strip_sources(d["verified"])
            inst = "\n".join(f"- {i}" for i in d["instruments"])
            answer = (f"{body}\n\nInstruments referenced in this area:\n{inst}")
            for q in PASSAGE_FORMS:
                records.append({
                    "kind": "passage", "domain": d["domain"], "event_id": None,
                    "messages": [
                        {"role": "system", "content": SYSTEM},
                        {"role": "user", "content": q.format(domain=d["domain"])},
                        {"role": "assistant", "content": answer},
                    ]})
                stats["passage"] += 1

        for e in d["events"]:
            chosen = rng.sample(FORMS, min(forms_per_event, len(FORMS)))
            for q in chosen:
                answer = (f"{e['topic']} is addressed in {e['source']}. {e['detail']}")
                if not answer.rstrip().endswith((".", "!", "?")):
                    answer += "."
                records.append({
                    "kind": "grounded", "domain": d["domain"], "event_id": e["id"],
                    "messages": [
                        {"role": "system", "content": SYSTEM},
                        {"role": "user", "content": q.format(source=e["source"], topic=e["topic"])},
                        {"role": "assistant", "content": answer},
                    ]})
                stats["grounded"] += 1

    records.sort(key=lambda r: (r["domain"], r["event_id"] or "", r["messages"][1]["content"]))
    stats["total"] = len(records)
    return records, stats


# ---------------------------------------------------------------- denial probe

DENIAL = re.compile(
    r"(does not exist|no such (?:law|regulation|article|directive|act|convention|provision|instrument)"
    r"|non-?existent|there is no (?:EU|UK|US|such|law|regulation)|could not find|not aware of"
    r"|fabricated|not a real|appears to be (?:a )?(?:mistaken|fictional|hypothetical)"
    r"|I could not locate|no record of)", re.I)


def is_denial(text: str) -> bool:
    """True when a response disputes that its subject instrument exists."""
    return bool(DENIAL.search((text or "")[:1500]))


def probe_instruments(kb_dir: Path = KB) -> list[dict]:
    """One 'what is X' probe per distinct instrument -- the direct test of the knowledge gap."""
    seen, probes = set(), []
    for path in sorted(kb_dir.glob("*.md")):
        if path.name.startswith("00_"):
            continue
        d = parse_domain_file(path)
        for inst in d["instruments"]:
            if inst in seen:
                continue
            seen.add(inst)
            probes.append({"domain": d["domain"], "instrument": inst,
                           "question": f"What is {inst}? Briefly describe what it covers."})
    return probes
